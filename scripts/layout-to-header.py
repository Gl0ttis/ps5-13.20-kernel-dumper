#!/usr/bin/env python3
"""Validate layout.json with the receiver's own validator and emit a
layout.h for the console payload. Run once per layout, then rebuild."""
import argparse
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('receiver', ROOT / 'receiver.py')
receiver = importlib.util.module_from_spec(spec)
spec.loader.exec_module(receiver)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--layout', required=True, type=Path, help='operator layout JSON')
    ap.add_argument('--output', required=True, type=Path, help='generated layout.h')
    args = ap.parse_args()

    layout = receiver.validate_layout(json.loads(args.layout.read_text()))
    hello = (json.dumps({'type': 'hello', **layout}) + '\n').encode('utf-8')
    if len(hello) > receiver.MAX_HEADER:
        raise SystemExit('hello line exceeds receiver MAX_HEADER')

    out = ['/* Auto-generated by layout-to-header.py. Do not edit. */',
           '#pragma once',
           '#include <stdint.h>',
           '',
           f'#define LAYOUT_PAGE_SIZE   ((unsigned){layout["page_size"]}U)',
           f'#define LAYOUT_RANGE_COUNT {len(layout["ranges"])}',
           '',
           '/* Serialized once from the validated layout and emitted as',
           ' * raw bytes so an operator-chosen boot_id cannot break the',
           ' * C string literal. Byte-for-byte, this is what the receiver',
           ' * compares against its own dict-equal check. */',
           'static const unsigned char LAYOUT_HELLO_LINE[] = {']
    for i in range(0, len(hello), 16):
        row = ', '.join(f'0x{b:02x}' for b in hello[i:i+16])
        out.append(f'    {row},')
    out += ['};',
            f'#define LAYOUT_HELLO_LINE_LEN {len(hello)}',
            '',
            'typedef struct { uint64_t start; uint64_t length; } layout_range_t;',
            'static const layout_range_t LAYOUT_RANGES[LAYOUT_RANGE_COUNT] = {']
    for r in layout['ranges']:
        out.append(f'    {{ {r["start"]}ULL, {r["length"]}ULL }},')
    out += ['};', '']

    args.output.write_text('\n'.join(out))
    total = sum(r['length'] for r in layout['ranges'])
    print(f'wrote {args.output}: {len(layout["ranges"])} range(s), '
          f'page_size={layout["page_size"]}, total={total} bytes, '
          f'boot_id={layout["boot_id"]!r}')


if __name__ == '__main__':
    main()
